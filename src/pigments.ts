export function pigmentName(code: string): string | undefined {
  return NAMES[code] ?? NAMES[code.replace(/:\d+$/, '')];
}

/** Sort codes by family then number: PY3 < PY35 < PO20 ... */
const FAMILY_ORDER = ['PW', 'PY', 'PO', 'PR', 'PV', 'PB', 'PG', 'PBr', 'PBk'];
export function comparePigments(a: string, b: string): number {
  const pa = a.match(/^([A-Z]+[a-z]*)(\d+)(?::(\d+))?/);
  const pb = b.match(/^([A-Z]+[a-z]*)(\d+)(?::(\d+))?/);
  if (!pa || !pb) return a.localeCompare(b);
  const fa = FAMILY_ORDER.indexOf(pa[1]);
  const fb = FAMILY_ORDER.indexOf(pb[1]);
  return (fa < 0 ? 99 : fa) - (fb < 0 ? 99 : fb) || pa[1].localeCompare(pb[1]) || +pa[2] - +pb[2] || +(pa[3] ?? 0) - +(pb[3] ?? 0);
}
